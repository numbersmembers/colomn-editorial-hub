export function buildEvaluatePrompt(draft: string): string {
  return EVALUATE_PROMPT_TEMPLATE.replace('{draft}', draft);
}

export function buildRewritePrompt(draft: string, feedback: string): string {
  return REWRITE_PROMPT_TEMPLATE
    .replace('{draft}', draft)
    .replace('{feedback}', feedback);
}
